    @Test
    fun matchesTheReferenceModuleForModule() {
        vectors.forEach { vector ->
            val matrix = QrMatrix.encode(vector.text.encodeToByteArray())
            assertEquals(vector.version, matrix.version, vector.text)
            assertEquals(vector.ecc, matrix.ecc, vector.text)
            assertEquals(vector.mask, matrix.mask, vector.text)
            val rows = (0 until matrix.size).map { y ->
                (0 until matrix.size).joinToString("") { x -> if (matrix.isDark(x, y)) "1" else "0" }
            }
            assertEquals(vector.rows, rows, vector.text)
        }
    }

    @Test
    fun moreThanTheLargestCodeHoldsIsRefused() {
        assertFailsWith<IllegalArgumentException> { QrMatrix.encode(ByteArray(2_954)) }
        assertEquals(40, QrMatrix.encode(ByteArray(2_953), QrMatrix.Ecc.LOW).version)
    }
